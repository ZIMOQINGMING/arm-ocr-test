# ========== 检索模拟 ==========

def mock_search(keyword, text):
    """
    模拟检索：检查 keyword 是否在 text 中出现（支持多关键词 AND 逻辑）
    返回 (命中, 命中关键词列表)
    """
    关键词 = keyword.split()
    matched = []
    for kw in 关键词:
        if fuzzy_in(kw, text):
            matched.append(kw)
    return len(matched) == len(关键词), matched


def load_archive_texts(archive_dir):
    """
    加载归档目录中的所有 txt 文件
    返回 {文件名: 内容}
    """
    texts = {}
    if not os.path.isdir(archive_dir):
        return texts
    for fname in os.listdir(archive_dir):
        if fname.endswith('.txt'):
            fpath = os.path.join(archive_dir, fname)
            try:
                with open(fpath, 'r', encoding='utf-8') as f:
                    texts[fname] = f.read()
            except Exception:
                pass
    return texts


